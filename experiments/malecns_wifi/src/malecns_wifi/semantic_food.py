"""Semantic trajectories and counterfactual semantic food for MaleCNS tagging.

The text is encoded by a pretrained semantic model before it reaches the frozen
connectome. Cumulative text chunks form a semantic trajectory; the connectome sees
small left-to-right changes in that trajectory rather than raw bytes.

A tag can also define a *counterfactual food signal*. At each checkpoint we encode
exactly the same text twice: once as-is and once conditioned on the tag. The vector

    food = E(text + tag) - E(text)

is the semantic displacement caused by the tag. Its norm is the amount of food;
its direction is the semantic flavour. The direction can be distributed across an
anatomically selected appetitive gustatory population while preserving a
non-negative total drive equal to the food amount. This does not require a gold
span at inference time and does not inject the answer into the model.

Gold spans remain useful as evaluation targets and for explicitly supervised
teacher ablations, but they are no longer the definition of food.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np


@dataclass(frozen=True)
class SemanticTrajectory:
    """Interpolated semantic path and its local motion."""

    states: np.ndarray
    deltas: np.ndarray
    chunk_index: np.ndarray


@dataclass(frozen=True)
class SemanticFoodSignal:
    """Tag-induced displacement along one semantic text trajectory.

    ``difference[t]`` is ``E(text+tag)[t] - E(text)[t]`` after interpolation.
    ``intensity`` is its L2 norm and therefore a scalar food amount. ``direction``
    is the unit vector carrying the semantic flavour; it is zero when intensity is
    zero. ``deltas`` records how the food vector itself changes over time.
    """

    base: SemanticTrajectory
    tagged: SemanticTrajectory
    difference: np.ndarray
    deltas: np.ndarray
    intensity: np.ndarray
    direction: np.ndarray


def interpolate_semantic_chunks(
    embeddings: np.ndarray,
    *,
    steps_per_transition: int = 8,
    normalise: bool = True,
) -> SemanticTrajectory:
    """Turn cumulative chunk embeddings into a smooth left-to-right trajectory."""
    vectors = np.asarray(embeddings, dtype=np.float32)
    if vectors.ndim != 2 or vectors.shape[0] < 1 or vectors.shape[1] < 1:
        raise ValueError("embeddings must have shape [chunks, dimensions]")
    if steps_per_transition < 1:
        raise ValueError("steps_per_transition must be >= 1")

    if normalise:
        norms = np.linalg.norm(vectors, axis=1, keepdims=True)
        vectors = vectors / np.maximum(norms, 1e-12)

    if len(vectors) == 1:
        states = vectors.copy()
        chunk_index = np.zeros(1, dtype=np.int32)
    else:
        pieces: list[np.ndarray] = [vectors[:1]]
        mapping: list[np.ndarray] = [np.zeros(1, dtype=np.int32)]
        for index in range(1, len(vectors)):
            alpha = np.linspace(
                1.0 / steps_per_transition,
                1.0,
                steps_per_transition,
                dtype=np.float32,
            )[:, None]
            segment = vectors[index - 1] + alpha * (vectors[index] - vectors[index - 1])
            pieces.append(segment.astype(np.float32, copy=False))
            mapping.append(np.full(steps_per_transition, index, dtype=np.int32))
        states = np.vstack(pieces)
        chunk_index = np.concatenate(mapping)

    deltas = np.empty_like(states)
    deltas[0] = 0.0
    if len(states) > 1:
        deltas[1:] = states[1:] - states[:-1]
    return SemanticTrajectory(states=states, deltas=deltas, chunk_index=chunk_index)


def counterfactual_tag_food(
    base_embeddings: np.ndarray,
    tagged_embeddings: np.ndarray,
    *,
    steps_per_transition: int = 8,
    normalise: bool = True,
) -> SemanticFoodSignal:
    """Compute semantic food as ``E(text+tag) - E(text)`` through time.

    Both arrays must be generated by the same encoder at the same cumulative text
    checkpoints. The function deliberately keeps the full vector difference rather
    than collapsing immediately to cosine similarity, because the direction may
    carry useful information about *which kind* of semantic relevance is present.
    """
    base_vectors = np.asarray(base_embeddings, dtype=np.float32)
    tagged_vectors = np.asarray(tagged_embeddings, dtype=np.float32)
    if base_vectors.shape != tagged_vectors.shape:
        raise ValueError("base and tagged embeddings must have identical shape")

    base = interpolate_semantic_chunks(
        base_vectors,
        steps_per_transition=steps_per_transition,
        normalise=normalise,
    )
    tagged = interpolate_semantic_chunks(
        tagged_vectors,
        steps_per_transition=steps_per_transition,
        normalise=normalise,
    )
    if not np.array_equal(base.chunk_index, tagged.chunk_index):
        raise AssertionError("counterfactual trajectories lost checkpoint alignment")

    difference = (tagged.states - base.states).astype(np.float32, copy=False)
    intensity = np.linalg.norm(difference, axis=1).astype(np.float32)
    direction = np.zeros_like(difference)
    active = intensity > 1e-12
    direction[active] = difference[active] / intensity[active, None]

    deltas = np.empty_like(difference)
    deltas[0] = 0.0
    if len(difference) > 1:
        deltas[1:] = difference[1:] - difference[:-1]

    return SemanticFoodSignal(
        base=base,
        tagged=tagged,
        difference=difference,
        deltas=deltas,
        intensity=intensity,
        direction=direction,
    )


def food_population_drive(
    signal: SemanticFoodSignal,
    food_indices: np.ndarray,
    *,
    seed: int = 0,
    amplitude: float = 1.0,
    temperature: float = 1.0,
) -> tuple[np.ndarray, np.ndarray]:
    """Encode semantic food as a non-negative distributed appetitive drive.

    A fixed seeded projection maps semantic *direction* to a population pattern.
    Softmax makes that pattern non-negative and normalised. Multiplying by the
    displacement norm makes the row sum exactly ``amplitude * intensity[t]``.
    Thus direction controls flavour, magnitude controls amount, and total injected
    drive is explicit and easy to match in anatomical/random controls.

    Returns ``(indices, drive)`` where ``drive`` has shape
    ``[time_steps, len(indices)]``. Full-brain code should scatter these values
    directly rather than allocate a dense ``time x neurons`` matrix.
    """
    food = np.asarray(food_indices, dtype=np.int64).reshape(-1)
    if food.size == 0:
        raise ValueError("food population is empty")
    if temperature <= 0:
        raise ValueError("temperature must be > 0")
    if amplitude < 0:
        raise ValueError("amplitude must be >= 0")

    dimensions = signal.direction.shape[1]
    rng = np.random.default_rng(seed)
    projection = rng.normal(size=(food.size, dimensions)).astype(np.float32)
    projection /= np.sqrt(max(dimensions, 1))

    logits = signal.direction @ projection.T
    logits = logits / np.float32(temperature)
    logits -= logits.max(axis=1, keepdims=True)
    weights = np.exp(logits).astype(np.float32)
    weights /= np.maximum(weights.sum(axis=1, keepdims=True), 1e-12)
    drive = weights * (signal.intensity[:, None] * np.float32(amplitude))
    return food, drive.astype(np.float32, copy=False)


def condition_on_tag(
    trajectory: SemanticTrajectory,
    tag_embedding: np.ndarray,
    *,
    include_absolute_state: bool = False,
) -> np.ndarray:
    """Attach the semantic identity of the tag being sought to every time step."""
    tag = np.asarray(tag_embedding, dtype=np.float32).reshape(-1)
    if tag.size != trajectory.deltas.shape[1]:
        raise ValueError("tag embedding must live in the same semantic space as the text")
    norm = np.linalg.norm(tag)
    if norm > 0:
        tag = tag / norm
    repeated = np.broadcast_to(tag, trajectory.deltas.shape)
    blocks = [trajectory.deltas]
    if include_absolute_state:
        blocks.append(trajectory.states)
    blocks.append(repeated)
    return np.concatenate(blocks, axis=1).astype(np.float32, copy=False)


def span_mask_from_chunks(
    chunk_index: np.ndarray,
    spans: list[tuple[int, int]] | tuple[tuple[int, int], ...],
) -> np.ndarray:
    """Project half-open chunk spans onto the interpolated recurrent time axis."""
    mapping = np.asarray(chunk_index)
    mask = np.zeros(mapping.shape, dtype=np.float32)
    for start, end in spans:
        if start < 0 or end <= start:
            raise ValueError(f"invalid chunk span {(start, end)}")
        mask[(mapping >= start) & (mapping < end)] = 1.0
    return mask


def edge_targets(mask: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """START/END impulses derived from one continuous consumption mask."""
    inside = np.asarray(mask, dtype=np.float32).reshape(-1)
    previous = np.concatenate([np.zeros(1, dtype=np.float32), inside[:-1]])
    following = np.concatenate([inside[1:], np.zeros(1, dtype=np.float32)])
    start = ((inside > 0) & (previous <= 0)).astype(np.float32)
    end = ((inside > 0) & (following <= 0)).astype(np.float32)
    return start, end


def matched_random_population(
    sensory_indices: np.ndarray,
    food_indices: np.ndarray,
    *,
    seed: int,
) -> np.ndarray:
    """Random sensory control matched exactly to the size of the food population."""
    sensory = np.asarray(sensory_indices, dtype=np.int64)
    food = np.asarray(food_indices, dtype=np.int64)
    candidates = np.setdiff1d(sensory, food, assume_unique=False)
    if food.size == 0:
        raise ValueError("food population is empty")
    if candidates.size < food.size:
        raise ValueError("not enough non-food sensory neurons for a matched control")
    rng = np.random.default_rng(seed)
    return np.sort(rng.choice(candidates, size=food.size, replace=False)).astype(np.int64)


def teacher_food_drive(
    neurons: int,
    time_steps: int,
    food_indices: np.ndarray,
    mask: np.ndarray,
    *,
    amplitude: float = 1.0,
) -> np.ndarray:
    """Gold-span food pulse retained only as a supervised teacher ablation."""
    food = np.asarray(food_indices, dtype=np.int64)
    active = np.asarray(mask, dtype=np.float32).reshape(-1)
    if food.size == 0:
        raise ValueError("food population is empty")
    if active.size != time_steps:
        raise ValueError("mask length must equal time_steps")
    if np.any(food < 0) or np.any(food >= neurons):
        raise ValueError("food index outside operator")
    drive = np.zeros((time_steps, neurons), dtype=np.float32)
    drive[:, food] = active[:, None] * np.float32(amplitude)
    return drive


# --- unsupervised food from the semantic space ------------------------------
#
# The teacher above needs an annotated span to know when to feed. The contrast
# below does not: the food signal comes from the encoder itself, by asking what
# the tag *does* to the reading of the text so far.
#
#     E_t     = f(text up to t)
#     E_t^tag = f(text up to t + tag)
#     F_t     = E_t^tag - E_t
#
# F_t is "what the presence of this tag changes about the interpretation here".
# Its direction is a flavour and its magnitude an amount, so START and END need
# not be declared: they are where the signal rises and falls.


@dataclass(frozen=True)
class TagContrast:
    """The tag-conditioned semantic contrast and its scalar intensity."""

    contrast: np.ndarray
    intensity: np.ndarray
    plain: np.ndarray
    tagged: np.ndarray
    intensity_mode: str


def tag_contrast(
    plain: np.ndarray,
    tagged: np.ndarray,
    tag_embedding: np.ndarray,
    *,
    intensity: str = "similarity",
    normalise: bool = True,
) -> TagContrast:
    """Contrast between reading the text with and without the tag appended.

    Both sequences are unit-normalised before differencing unless disabled, so the
    contrast is a movement on the sphere and is comparable across positions rather
    than tracking encoder magnitude.

    Three intensity definitions are offered because their polarity is not the
    same, and two of them are probably backwards. If the text is already about the
    tag, appending the tag is redundant and moves the embedding very little, so
    ``norm`` and ``alignment`` are expected to be *largest where the text is least
    related* -- inverting the intended "this passage starts to taste like the
    tag". ``similarity``, the plain cosine between text and tag, has the intended
    polarity by construction. Which one actually tracks annotated spans is an
    empirical question: measure it with :func:`intensity_polarity` on gold
    documents before choosing, and do not assume the sign.

    * ``norm``       -- ``||F_t||``
    * ``alignment``  -- ``<F_t, tag_hat>``
    * ``similarity`` -- ``<E_t_hat, tag_hat>`` (default)
    """
    left = np.asarray(plain, dtype=np.float32)
    right = np.asarray(tagged, dtype=np.float32)
    if left.ndim != 2 or left.shape != right.shape:
        raise ValueError("plain and tagged embeddings must share shape [steps, dimensions]")
    tag = np.asarray(tag_embedding, dtype=np.float32).reshape(-1)
    if tag.size != left.shape[1]:
        raise ValueError("tag embedding must live in the same semantic space as the text")

    if normalise:
        left = left / np.maximum(np.linalg.norm(left, axis=1, keepdims=True), 1e-12)
        right = right / np.maximum(np.linalg.norm(right, axis=1, keepdims=True), 1e-12)
    tag_hat = tag / max(float(np.linalg.norm(tag)), 1e-12)

    contrast = (right - left).astype(np.float32)
    if intensity == "norm":
        values = np.linalg.norm(contrast, axis=1)
    elif intensity == "alignment":
        values = contrast @ tag_hat
    elif intensity == "similarity":
        unit = left / np.maximum(np.linalg.norm(left, axis=1, keepdims=True), 1e-12)
        values = unit @ tag_hat
    else:
        raise ValueError(f"unknown intensity mode {intensity!r}")

    return TagContrast(
        contrast=contrast,
        intensity=values.astype(np.float32),
        plain=left,
        tagged=right,
        intensity_mode=intensity,
    )


def intensity_polarity(intensity: np.ndarray, mask: np.ndarray) -> dict:
    """Does this intensity rise or fall inside the annotated region?

    Settles the polarity question by measurement instead of argument. A negative
    ``point_biserial`` means the signal is *lower* where the tag applies, so that
    definition is inverted and feeding on it would starve the fly exactly where
    the answer is.
    """
    values = np.asarray(intensity, dtype=np.float64).reshape(-1)
    inside = np.asarray(mask, dtype=bool).reshape(-1)
    if values.size != inside.size:
        raise ValueError("intensity and mask must share length")
    if inside.all() or not inside.any():
        return {
            "point_biserial": 0.0,
            "inside_mean": 0.0,
            "outside_mean": 0.0,
            "separation": 0.0,
            "degenerate": True,
        }
    correlation = (
        0.0
        if values.std() < 1e-12
        else float(np.corrcoef(values, inside.astype(np.float64))[0, 1])
    )
    return {
        "point_biserial": correlation,
        "inside_mean": float(values[inside].mean()),
        "outside_mean": float(values[~inside].mean()),
        "separation": float(values[inside].mean() - values[~inside].mean()),
        "degenerate": False,
    }


def contrast_food_drive(
    contrast: TagContrast,
    food_indices: np.ndarray,
    *,
    seed: int,
    amplitude: float = 1.0,
    separate_flavour_from_amount: bool = True,
) -> np.ndarray:
    """Project the contrast onto the gustatory population: direction is flavour.

    The whole vector is projected rather than reduced to a scalar first, so
    different semantic directions produce different patterns across the food
    neurons -- distinct tastes, not merely more or less food. With
    ``separate_flavour_from_amount`` the pattern is unit-normalised and then scaled
    by the intensity, keeping "which flavour" and "how much" independently
    controlled; without it the raw projection carries both at once.

    The projection is a fixed seeded random matrix: part of the frozen interface,
    never fitted.
    """
    food = np.asarray(food_indices, dtype=np.int64)
    if food.size == 0:
        raise ValueError("food population is empty")
    dimensions = contrast.contrast.shape[1]
    rng = np.random.default_rng(seed)
    projection = rng.normal(
        scale=1.0 / np.sqrt(dimensions), size=(dimensions, food.size)
    ).astype(np.float32)

    pattern = contrast.contrast @ projection
    if separate_flavour_from_amount:
        norms = np.maximum(np.linalg.norm(pattern, axis=1, keepdims=True), 1e-12)
        pattern = pattern / norms * contrast.intensity[:, None]
    return (pattern * np.float32(amplitude)).astype(np.float32)


def direct_control_features(trajectory: SemanticTrajectory, contrast: TagContrast) -> np.ndarray:
    """``[E_t, F_t, dE_t]`` -- everything the fly is given, with no fly.

    The mandatory control for this formulation. If a classifier on these features
    already delimits the region cleanly, the encoder solved the tagging and the
    connectome is decoration. The interesting result is the connectome improving
    continuity, edges, or the temporal decision over a noisy signal, and that
    claim is only available once this control has been run and lost.
    """
    if trajectory.states.shape[0] != contrast.contrast.shape[0]:
        raise ValueError("trajectory and contrast must share the time axis")
    return np.concatenate(
        [trajectory.states, contrast.contrast, trajectory.deltas], axis=1
    ).astype(np.float32)
